 ### 3\. Check the inserted data

```
SELECT *
FROM FACT_SALES
ORDER BY SALE_DATE;
```

 ### 4\. Run your actual query


SELECT *
FROM FACT_SALES
WHERE SALE_DATE BETWEEN DATE '2026-01-01'
                    AND DATE '2026-01-31';

 You should get all **30 records**.

 ### 5\. Add the clustering key


ALTER TABLE FACT_SALES
CLUSTER BY (SALE_DATE);


 ### 6\. Check the clustering key

SHOW TABLES LIKE 'FACT_SALES';

--Look for the `cluster_by` column. It should show something similar to:

LINEAR(SALE_DATE)

---### 7\. Check clustering information


SELECT SYSTEM$CLUSTERING_INFORMATION('FACT_SALES');


 ### 8\. Check clustering depth


SELECT SYSTEM$CLUSTERING_DEPTH('FACT_SALES');


 ### Complete order

 Run them in this order:

```
1. CREATE TABLE
       ↓
2. INSERT DATA
       ↓
3. SELECT DATA
       ↓
4. Run SALE_DATE filter query
       ↓
5. ALTER TABLE ... CLUSTER BY
       ↓
6. SHOW TABLES
       ↓
7. SYSTEM$CLUSTERING_INFORMATION
       ↓
8. SYSTEM$CLUSTERING_DEPTH
```

 **One thing to remember:** with only 30 rows, you probably won't see a meaningful clustering benefit. This example is mainly for **learning and verifying the commands**. In a real scenario, clustering is more useful with large tables containing many micro-partitions.